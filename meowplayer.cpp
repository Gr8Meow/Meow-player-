    opt("input-default-bindings", "no");
    opt("input-vo-keyboard", "yes");
    opt("input-media-keys", "no");  // global media keys are handled by this app
    opt("ytdl", "no");              // never launch external programs
    opt("load-scripts", "no");
    opt("cursor-autohide", "1000");
    opt("keep-open", "no");
    opt("audio-display", "embedded-first");
    opt("volume-max", "130");
