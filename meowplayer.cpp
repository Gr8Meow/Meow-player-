template <typename T>
static bool LoadFn(T& fn, const char* name) {
    FARPROC p = GetProcAddress(mpv.dll, name);
    fn = reinterpret_cast<T>(reinterpret_cast<void*>(p));
    return fn != nullptr;
}

static bool LoadMpvDll() {
    wchar_t exe[MAX_PATH];
    GetModuleFileNameW(nullptr, exe, MAX_PATH);
    PathRemoveFileSpecW(exe);
    std::wstring path = std::wstring(exe) + L"\\libmpv-2.dll";
    mpv.dll = LoadLibraryExW(path.c_str(), nullptr, LOAD_WITH_ALTERED_SEARCH_PATH);
    if (!mpv.dll) {
        g_mpvStatus = L"libmpv-2.dll not found next to the exe";
        return false;
    }
    bool ok = LoadFn(mpv.create, "mpv_create") && LoadFn(mpv.initialize, "mpv_initialize") &&
              LoadFn(mpv.terminate_destroy, "mpv_terminate_destroy") &&
              LoadFn(mpv.set_option_string, "mpv_set_option_string") &&
              LoadFn(mpv.set_property_string, "mpv_set_property_string") &&
              LoadFn(mpv.get_property, "mpv_get_property") &&
              LoadFn(mpv.get_property_string, "mpv_get_property_string") &&
              LoadFn(mpv.free, "mpv_free") && LoadFn(mpv.command, "mpv_command") &&
              LoadFn(mpv.observe_property, "mpv_observe_property") &&
              LoadFn(mpv.wait_event, "mpv_wait_event") &&
              LoadFn(mpv.set_wakeup_callback, "mpv_set_wakeup_callback") &&
              LoadFn(mpv.client_api_version, "mpv_client_api_version");
    if (!ok) {
        g_mpvStatus = L"libmpv-2.dll is not a compatible version";
        FreeLibrary(mpv.dll);
        mpv.dll = nullptr;
        return false;
    }
    return true;
}

