static void LoadSettings() {
    FILE* f = _wfopen(ConfigPath().c_str(), L"rb");
    if (!f) return;
    std::string data;
    char buf[4096];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        data.append(buf, n);
        if (data.size() > 8u * 1024u * 1024u) break;  // settings are small; refuse huge files
    }
    fclose(f);
    size_t pos = 0;
    while (pos < data.size()) {
        size_t end = data.find('\n', pos);
        if (end == std::string::npos) end = data.size();
        std::string line = data.substr(pos, end - pos);
        pos = end + 1;
        if (!line.empty() && line.back() == '\r') line.pop_back();
        size_t eq = line.find('=');
        if (eq == std::string::npos) continue;
        std::string k = line.substr(0, eq), v = line.substr(eq + 1);
        int iv = atoi(v.c_str());
        if (k == "theme") g_s.theme = iv;
        else if (k == "volume") g_s.volume = iv;
        else if (k == "mute") g_s.mute = iv != 0;
        else if (k == "shuffle") g_s.shuffle = iv != 0;
        else if (k == "repeat") g_s.repeat = iv;
        else if (k == "speed") g_s.speedIdx = iv;
        else if (k == "hwdec") g_s.hwdec = iv != 0;
        else if (k == "savePower") g_s.savePower = iv != 0;
        else if (k == "onTop") g_s.onTop = iv != 0;
        else if (k == "resume") g_s.resume = iv != 0;
        else if (k == "showQueue") g_s.showQueue = iv != 0;
        else if (k == "subScale") g_s.subScale = iv;
        else if (k == "subFont") g_s.subFont = iv;
        else if (k == "subBox") g_s.subBox = iv != 0;
        else if (k == "checkUpdates") g_s.checkUpdates = iv != 0;
        else if (k == "lastCheck") g_s.lastCheck = atoll(v.c_str());
        else if (k == "latestTag") g_s.latestTag = UC_ValidTag(v) ? v : "";
        else if (k == "skipTag") g_s.skipTag = UC_ValidTag(v) ? v : "";
        else if (k == "current") g_s.current = iv;
        else if (k == "pos") g_s.pos = atof(v.c_str());
        else if (k == "item") {
            Item it;
            it.path = FromUtf8(v);
            it.ok = GetFileAttributesW(it.path.c_str()) != INVALID_FILE_ATTRIBUTES;
            if (!it.path.empty() && g_list.size() < 20000) g_list.push_back(it);
        }
    }
    if (g_s.theme < 0 || g_s.theme >= kThemeCount) g_s.theme = 0;
    g_s.volume = max(0, min(130, g_s.volume));
    if (g_s.repeat < 0 || g_s.repeat > 2) g_s.repeat = 1;
    if (g_s.speedIdx < 0 || g_s.speedIdx >= kSpeedCount) g_s.speedIdx = 2;
    if (!(g_s.pos >= 0) || g_s.pos > 360000.0) g_s.pos = 0;
    g_s.subScale = max(40, min(250, g_s.subScale));
    if (g_s.subFont < 0 || g_s.subFont >= kSubFontCount) g_s.subFont = 0;
}

