static void RoundPath(GraphicsPath& p, RectF r, float rad) {
    float d = min(rad * 2.0f, min(r.Width, r.Height));
    if (d <= 0.5f) {
        p.AddRectangle(r);
        return;
    }
    p.AddArc(r.X, r.Y, d, d, 180, 90);
    p.AddArc(r.X + r.Width - d, r.Y, d, d, 270, 90);
    p.AddArc(r.X + r.Width - d, r.Y + r.Height - d, d, d, 0, 90);
    p.AddArc(r.X, r.Y + r.Height - d, d, d, 90, 90);
    p.CloseFigure();
}
static void FillRR(RectF r, float rad, Color c) {
    GraphicsPath p;
    RoundPath(p, r, rad);
    SolidBrush b(c);
    G->FillPath(&b, &p);
}
static void StrokeRR(RectF r, float rad, Color c, float w) {
    GraphicsPath p;
    RoundPath(p, r, rad);
    Pen pen(c, w);
    G->DrawPath(&pen, &p);
}

