// ============================================================== key actions ===
static void DoAction(const std::string& a) {
    std::string cmd = a, arg;
    size_t sp = a.find(' ');
    if (sp != std::string::npos) {
        cmd = a.substr(0, sp);
        arg = a.substr(sp + 1);
    }
    if (cmd == "playpause") TogglePlay();
    else if (cmd == "seek") MpvCmd("seek", arg.c_str());
    else if (cmd == "vol") {
        g_s.volume = max(0, min(130, g_s.volume + atoi(arg.c_str())));
        g_s.mute = false;
        ApplyPlayerSettings();
    } else if (cmd == "mute") {
        g_s.mute = !g_s.mute;
        ApplyPlayerSettings();
    } else if (cmd == "full") ToggleFullscreen();
    else if (cmd == "esc") {
        if (g_fullscreen) ToggleFullscreen();
        else if (g_view == VIEW_SETTINGS) { g_view = VIEW_PLAYER; LayoutVideo(); }
    } else if (cmd == "next") NextTrack(false);
    else if (cmd == "prev") PrevTrack();
    else if (cmd == "speed") {
        g_s.speedIdx = max(0, min(kSpeedCount - 1, g_s.speedIdx + (arg == "+" ? 1 : -1)));
        ApplyPlayerSettings();
    } else if (cmd == "sub") MpvCmd("cycle", "sub");
    else if (cmd == "audio") MpvCmd("cycle", "audio");
    else if (cmd == "subdelay") MpvCmd("add", "sub-delay", arg.c_str());
    else if (cmd == "subvis") MpvCmd("cycle", "sub-visibility");
    else if (cmd == "stop") MpvCmd("stop");
    SaveSettings();
    InvalidateUI();
}

