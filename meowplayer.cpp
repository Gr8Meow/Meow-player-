// Official builds have the repository baked in (version.h, made by the GitHub build).
// Test and fork builds without it read "owner/repo" from update-repo.txt next to the exe.
static std::string g_updateRepo;

static void InitUpdateRepo() {
    g_updateRepo = UPDATE_REPO;
    if (!g_updateRepo.empty()) return;  // a baked-in repository can never be overridden
    wchar_t exe[MAX_PATH];
    GetModuleFileNameW(nullptr, exe, MAX_PATH);
    PathRemoveFileSpecW(exe);
    FILE* f = _wfopen((std::wstring(exe) + L"\\update-repo.txt").c_str(), L"rb");
    if (!f) return;
    char buf[256] = {0};
    size_t n = fread(buf, 1, sizeof(buf) - 1, f);
    fclose(f);
    std::string line(buf, n);
    if (line.compare(0, 3, "\xEF\xBB\xBF") == 0) line.erase(0, 3);  // UTF-8 BOM
    size_t end = line.find_first_of("\r\n");
    if (end != std::string::npos) line.erase(end);
    while (!line.empty() && (line.back() == ' ' || line.back() == '\t')) line.pop_back();
    while (!line.empty() && (line.front() == ' ' || line.front() == '\t')) line.erase(0, 1);
    if (UC_ValidRepo(line)) g_updateRepo = line;
}

static bool UpdateEnabled() { return UC_ValidRepo(g_updateRepo) && strncmp(APP_VERSION, "0.0.0", 5) != 0; }
static bool UpdateNoticeVisible() { return g_upState == UP_AVAILABLE && g_upTag != g_s.skipTag; }

