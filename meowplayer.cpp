// ============================================================== queue logic ===
static int AddFiles(const std::vector<std::wstring>& files) {
    int first = -1;
    for (const std::wstring& f : files) {
        int idx = -1;
        for (size_t i = 0; i < g_list.size(); i++)
            if (lstrcmpiW(g_list[i].path.c_str(), f.c_str()) == 0) { idx = (int)i; break; }
        if (idx < 0) {
            if (g_list.size() >= 20000) break;
            Item it;
            it.path = f;
            it.ok = GetFileAttributesW(f.c_str()) != INVALID_FILE_ATTRIBUTES;
            g_list.push_back(it);
            idx = (int)g_list.size() - 1;
        }
        if (first < 0) first = idx;
    }
    return first;
}

static void ScanFolder(const std::wstring& dir, std::vector<std::wstring>& out, int depth) {
    WIN32_FIND_DATAW fd;
    HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
    if (h == INVALID_HANDLE_VALUE) return;
    std::vector<std::wstring> mine;
    do {
        std::wstring name = fd.cFileName;
        if (name == L"." || name == L"..") continue;
        std::wstring full = dir + L"\\" + name;
        if (fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) {
            if (depth < 4 && !(fd.dwFileAttributes & FILE_ATTRIBUTE_REPARSE_POINT)) ScanFolder(full, out, depth + 1);
        } else if (IsMediaFile(full)) {
            mine.push_back(full);
        }
    } while (FindNextFileW(h, &fd) && out.size() < 20000);
    FindClose(h);
    std::sort(mine.begin(), mine.end(),
              [](const std::wstring& a, const std::wstring& b) { return StrCmpLogicalW(a.c_str(), b.c_str()) < 0; });
    out.insert(out.end(), mine.begin(), mine.end());
}

static bool IsSubtitleFile(const std::wstring& path) {
    static const wchar_t* exts[] = {L".srt", L".ass", L".ssa", L".vtt", L".sub", L".sup", L".idx", L".smi", L".sbv"};
    const wchar_t* e = PathFindExtensionW(path.c_str());
    for (const wchar_t* x : exts)
        if (lstrcmpiW(e, x) == 0) return true;
    return false;
}

static void AddSubtitleFiles(const std::vector<std::wstring>& files) {
    if (!g_h || g_idle) {
        g_status = L"Open a video first, then add subtitles";
        return;
    }
    int added = 0;
    for (const std::wstring& f : files) {
        std::string p = ToUtf8(f);
        MpvCmd("sub-add", p.c_str(), "cached");
        added++;
    }
    if (added) {
        MpvSet("sub-visibility", "yes");
        RefreshTracks();
        g_panelTab = 1;
        g_s.showQueue = true;
        g_status.clear();
    }
}

static void OpenPaths(const std::vector<std::wstring>& allPaths, bool play) {
    std::vector<std::wstring> paths, subs;
    for (const std::wstring& p : allPaths) (IsSubtitleFile(p) ? subs : paths).push_back(p);
    std::vector<std::wstring> files;
    for (const std::wstring& p : paths) {
        DWORD attr = GetFileAttributesW(p.c_str());
        if (attr == INVALID_FILE_ATTRIBUTES) continue;
        if (attr & FILE_ATTRIBUTE_DIRECTORY) ScanFolder(p, files, 0);
        else files.push_back(p);  // files you pick yourself are never filtered by extension
    }
    int first = AddFiles(files);
    if (!files.empty()) {
        g_pendingSubs = subs;  // attached as soon as the new video has loaded
        subs.clear();
    }
    if (first >= 0 && play) {
        g_sel = first;
        PlayIndex(first);
    }
    if (!subs.empty()) AddSubtitleFiles(subs);
    SaveSettings();
}

