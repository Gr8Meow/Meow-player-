static Bitmap* FindIcon(const char* name) {
    char key[64];
    strncpy(key, name, sizeof(key) - 1);
    key[sizeof(key) - 1] = 0;
    for (char* p = key; *p; p++)
        if (*p == '-') *p = '_';
    for (size_t i = 0; i < ARRAYSIZE(kIcons); i++)
        if (strcmp(kIcons[i].name, key) == 0) return g_iconBmp[i];
    return nullptr;
}

