static std::wstring OpenWithKey() { return L"Software\\Classes\\Applications\\" + ExeName(); }

static bool OpenWithRegistered() {
    HKEY key;
    bool ok = RegOpenKeyExW(HKEY_CURRENT_USER, (OpenWithKey() + L"\\shell\\open\\command").c_str(), 0,
                            KEY_READ, &key) == ERROR_SUCCESS;
    if (ok) RegCloseKey(key);
    return ok;
}

static void SetRegString(HKEY root, const std::wstring& sub, const wchar_t* name, const std::wstring& v) {
    HKEY key;
    if (RegCreateKeyExW(root, sub.c_str(), 0, nullptr, 0, KEY_WRITE, nullptr, &key, nullptr) == ERROR_SUCCESS) {
        RegSetValueExW(key, name, 0, REG_SZ, (const BYTE*)v.c_str(), (DWORD)((v.size() + 1) * sizeof(wchar_t)));
        RegCloseKey(key);
    }
}

static void SetOpenWith(bool enable) {
    std::wstring base = OpenWithKey();
    if (!enable) {
        SHDeleteKeyW(HKEY_CURRENT_USER, base.c_str());
        return;
    }
    wchar_t exe[MAX_PATH];
    GetModuleFileNameW(nullptr, exe, MAX_PATH);
    SetRegString(HKEY_CURRENT_USER, base, L"FriendlyAppName", kAppName);
    SetRegString(HKEY_CURRENT_USER, base + L"\\shell\\open\\command", nullptr,
                 L"\"" + std::wstring(exe) + L"\" \"%1\"");
    for (const wchar_t* ext : kMediaExts) SetRegString(HKEY_CURRENT_USER, base + L"\\SupportedTypes", ext, L"");
    SHChangeNotify(SHCNE_ASSOCCHANGED, SHCNF_IDLIST, nullptr, nullptr);
}

