    opt("cache", "yes");
    opt("demuxer-max-bytes", "64MiB");
    opt("demuxer-max-back-bytes", "32MiB");
    opt("sub-auto", "fuzzy");
    opt("drag-and-drop", "no");
    opt("resume-playback", "no");
    opt("save-position-on-quit", "no");
    opt("force-window", "no");
    if (mpv.initialize(g_h) < 0) {
        g_mpvStatus = L"could not start the player";
        g_h = nullptr;
        return false;
    }
    mpv.observe_property(g_h, 1, "time-pos", MPV_FORMAT_DOUBLE);
    mpv.observe_property(g_h, 2, "duration", MPV_FORMAT_DOUBLE);
    mpv.observe_property(g_h, 3, "pause", MPV_FORMAT_FLAG);
    mpv.observe_property(g_h, 4, "idle-active", MPV_FORMAT_FLAG);
    mpv.observe_property(g_h, 5, "aid", MPV_FORMAT_STRING);
    mpv.observe_property(g_h, 6, "sid", MPV_FORMAT_STRING);
    mpv.observe_property(g_h, 7, "sub-delay", MPV_FORMAT_DOUBLE);
