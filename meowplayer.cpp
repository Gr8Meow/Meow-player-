static void MpvCmd(const char* a, const char* b = nullptr, const char* c = nullptr,
                   const char* d = nullptr, const char* e = nullptr) {
    if (!g_h) return;
    const char* args[7] = {a, b, c, d, e, nullptr, nullptr};
    mpv.command(g_h, args);
}

static void MpvSet(const char* name, const char* value) {
    if (g_h) mpv.set_property_string(g_h, name, value);
}

static std::string MpvGetStr(const char* name) {
    if (!g_h) return "";
    char* s = mpv.get_property_string(g_h, name);
    std::string r = s ? s : "";
    if (s) mpv.free(s);
    return r;
}

