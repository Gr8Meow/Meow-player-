static RectF g_stage(0, 0, 0, 0), g_queueRect(0, 0, 0, 0), g_ctrlRect(0, 0, 0, 0);

static void ComputeLayout(int W, int H) {
    float ctrlTop = (float)(H - S(CTRL_H + 16));
    g_ctrlRect = RectF((float)S(PAD), ctrlTop, (float)(W - 2 * S(PAD)), (float)S(CTRL_H));
    bool q = g_s.showQueue && g_view == VIEW_PLAYER;
    float qw = q ? (float)S(QUEUE_W) : 0.0f;
    float top = (float)S(HEADER_H);
    float h = max(ctrlTop - top - S(12), 60.0f);
    float stageW = (float)(W - 2 * S(PAD)) - (q ? qw + S(14) : 0.0f);
    g_stage = RectF((float)S(PAD), top, max(stageW, 100.0f), h);
    g_queueRect = q ? RectF((float)(W - S(PAD)) - qw, top, qw, h) : RectF(0, 0, 0, 0);
}

static void LayoutVideo() {
    if (!g_video || !g_main) return;
    RECT rc;
    GetClientRect(g_main, &rc);
    ComputeLayout(rc.right, rc.bottom);
    if (g_fullscreen && !g_hasVideo) {
        // fullscreen without video makes no sense: leave it (handled by caller)
    }
    if (g_hasVideo && (g_view == VIEW_PLAYER || g_fullscreen)) {
        if (g_fullscreen) {
            MoveWindow(g_video, 0, 0, rc.right, rc.bottom, TRUE);
        } else {
            MoveWindow(g_video, (int)g_stage.X, (int)g_stage.Y, (int)g_stage.Width, (int)g_stage.Height, TRUE);
        }
        ShowWindow(g_video, SW_SHOWNA);
    } else {
        ShowWindow(g_video, SW_HIDE);
    }
}

static void ToggleFullscreen() {
    if (!g_hasVideo && !g_fullscreen) return;
    if (!g_fullscreen) {
        g_wpPrev.length = sizeof(g_wpPrev);
        GetWindowPlacement(g_main, &g_wpPrev);
        g_stylePrev = GetWindowLongW(g_main, GWL_STYLE);
        MONITORINFO mi;
        mi.cbSize = sizeof(mi);
        GetMonitorInfoW(MonitorFromWindow(g_main, MONITOR_DEFAULTTONEAREST), &mi);
        SetWindowLongW(g_main, GWL_STYLE, g_stylePrev & ~WS_OVERLAPPEDWINDOW);
        SetWindowPos(g_main, HWND_TOP, mi.rcMonitor.left, mi.rcMonitor.top,
                     mi.rcMonitor.right - mi.rcMonitor.left, mi.rcMonitor.bottom - mi.rcMonitor.top,
                     SWP_NOOWNERZORDER | SWP_FRAMECHANGED);
        g_fullscreen = true;
    } else {
        SetWindowLongW(g_main, GWL_STYLE, g_stylePrev);
        SetWindowPlacement(g_main, &g_wpPrev);
        SetWindowPos(g_main, nullptr, 0, 0, 0, 0,
                     SWP_NOMOVE | SWP_NOSIZE | SWP_NOZORDER | SWP_NOOWNERZORDER | SWP_FRAMECHANGED);
        g_fullscreen = false;
    }
    LayoutVideo();
    InvalidateUI();
}

