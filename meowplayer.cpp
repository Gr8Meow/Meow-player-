static std::wstring FmtTime(double t) {
    if (!(t > 0) || t > 360000.0) t = 0;
    int s = (int)t, h = s / 3600, m = (s / 60) % 60, sec = s % 60;
    wchar_t b[32];
    if (h > 0) _snwprintf(b, 32, L"%d:%02d:%02d", h, m, sec);
    else _snwprintf(b, 32, L"%d:%02d", m, sec);
    return b;
}

