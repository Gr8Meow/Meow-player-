static void LoadIndex(int i, double startPos, bool startPaused) {
    if (!g_h || i < 0 || i >= (int)g_list.size()) return;
    g_cur = i;
    g_status.clear();
    g_pos = startPos;
    g_dur = 0;
    std::string path = ToUtf8(g_list[i].path);
    if (startPos > 1.0 || startPaused) {
        char opt[64];
        snprintf(opt, sizeof(opt), "start=%.2f,pause=%s", startPos, startPaused ? "yes" : "no");
        MpvCmd("loadfile", path.c_str(), "replace", "-1", opt);
    } else {
        MpvSet("pause", "no");
        MpvCmd("loadfile", path.c_str(), "replace");
    }
    SaveSettings();
    InvalidateUI();
}

static void PlayIndex(int i) { LoadIndex(i, 0, false); }

static void NextTrack(bool fromEnd) {
    int n = (int)g_list.size();
    if (n == 0) return;
    int idx;
    if (g_s.shuffle && n > 1) {
        do { idx = rand() % n; } while (idx == g_cur);
    } else {
        idx = g_cur + 1;
    }
    if (idx >= n) {
        if (g_s.repeat == 1 || !fromEnd) idx = 0;
        else {  // end of queue with repeat off: stop
            MpvCmd("stop");
            return;
        }
    }
    PlayIndex(idx);
}

static void PrevTrack() {
    int n = (int)g_list.size();
    if (n == 0) return;
    if (g_pos > 3.0 && !g_idle) {
        MpvCmd("seek", "0", "absolute");
        return;
    }
    PlayIndex((g_cur - 1 + n) % n);
}

static void TogglePlay() {
    if (g_idle) {
        if (!g_list.empty()) PlayIndex(g_cur >= 0 && g_cur < (int)g_list.size() ? g_cur : 0);
    } else {
        MpvCmd("cycle", "pause");
    }
}

static void RefreshTracks() {
    g_nAudio = g_nSub = 0;
    g_subs.clear();
    int64_t count = 0;
    if (!g_h || mpv.get_property(g_h, "track-list/count", MPV_FORMAT_INT64, &count) < 0) return;
    for (int i = 0; i < count && i < 512; i++) {
        char name[96];
        snprintf(name, sizeof(name), "track-list/%d/type", i);
        std::string t = MpvGetStr(name);
        if (t == "audio") {
            g_nAudio++;
        } else if (t == "sub") {
            g_nSub++;
            SubTrack st;
            snprintf(name, sizeof(name), "track-list/%d/id", i);
            mpv.get_property(g_h, name, MPV_FORMAT_INT64, &st.id);
            snprintf(name, sizeof(name), "track-list/%d/title", i);
            std::wstring title = FromUtf8(MpvGetStr(name));
            snprintf(name, sizeof(name), "track-list/%d/lang", i);
            std::wstring lang = FromUtf8(MpvGetStr(name));
            snprintf(name, sizeof(name), "track-list/%d/external", i);
            st.external = MpvGetStr(name) == "yes";
            if (st.external) {
                snprintf(name, sizeof(name), "track-list/%d/external-filename", i);
                std::wstring file = FromUtf8(MpvGetStr(name));
                if (!file.empty()) title = PathFindFileNameW(file.c_str());
            }
            if (!title.empty() && !lang.empty()) st.label = title + L" (" + lang + L")";
            else if (!title.empty()) st.label = title;
            else if (!lang.empty()) st.label = lang;
            else st.label = L"Subtitle " + std::to_wstring((long long)st.id);
            g_subs.push_back(st);
        }
    }
}

